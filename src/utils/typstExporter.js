import compilerWasmUrl from '@myriaddreamin/typst-ts-web-compiler/wasm?url';

const FONT_FILES = ['NotoSans-Regular.ttf', 'NotoSans-Bold.ttf'];
const FONT_FAMILY = 'Noto Sans';

// Typst string literal: safe for arbitrary text (no markup/math interpretation)
const str = (s) => `"${String(s ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

function mathProblem(p) {
    return `#block(breakable: false, below: 7mm)[#text(size: 15pt, weight: "bold")[#${str(p.number + '.')}] #h(2mm) #text(size: 16pt)[#${str(p.question)}]]`;
}

function wordProblem(p) {
    return `#block(breakable: false, below: 6mm)[#grid(columns: (9mm, 1fr), column-gutter: 1mm, text(weight: "bold")[#${str(p.number + '.')}], text(size: 12pt)[#${str(p.question)}])]`;
}

function answerItem(p) {
    return `#block(breakable: false)[#text(weight: "bold")[#${str(p.number + '.')}] #h(1mm) #${str(p.answer)}]`;
}

export function buildTypstSource(problems, config) {
    const math = problems.filter((p) => !p.isWordProblem);
    const words = problems.filter((p) => p.isWordProblem);
    const both = math.length > 0 && words.length > 0;
    const title = config.worksheetTitle || 'Worksheet';
    const wordsHeading = math.length > 0 ? 'Section B: Word Problems' : 'Word Problems';

    const out = [];
    out.push(`
#set document(title: ${str(title)})
#set page(
  paper: "a4",
  margin: (x: 15mm, top: 15mm, bottom: 22mm),
  footer: context {
    set text(size: 9pt, fill: luma(100), style: "italic")
    line(length: 100%, stroke: 0.5pt + luma(200))
    v(-1mm)
    let ak = query(<answer-key-start>)
    let in-key = ak.len() > 0 and here().page() >= ak.first().location().page()
    let total = if ak.len() == 0 or in-key { counter(page).final().first() } else { ak.first().location().page() - 1 }
    grid(columns: (1fr, 1fr), align: (left, right),
      [Page #counter(page).get().first() of #total],
      [Generated by WorksheetLoom.com])
  },
)
#set text(font: ${str(FONT_FAMILY)}, size: 11pt, fill: luma(40), lang: "en")
#set par(leading: 0.7em)
#let heading-section(t) = block(above: 6mm, below: 5mm, sticky: true, text(size: 13pt, weight: "bold", t))
#let meta-field(label, w) = box(width: w)[#label #box(width: 1fr, stroke: (bottom: 0.6pt + luma(60)), height: 1em)]

#align(center, text(size: 24pt, weight: "bold", ${str(title)}))
#v(2mm)
#grid(columns: (3fr, 2fr, 2fr), column-gutter: 8mm,
  meta-field("Name:", 100%), meta-field("Class:", 100%), meta-field("Date:", 100%))
#v(4mm)
#line(length: 100%, stroke: 1pt + luma(60))
#v(2mm)
`);

    if (math.length > 0) {
        if (both) out.push(`#heading-section(${str('Section A: Number Problems')})`);
        out.push(`#columns(2, gutter: 14mm)[\n${math.map(mathProblem).join('\n')}\n]`);
    }
    if (words.length > 0) {
        out.push(`#heading-section(${str(wordsHeading)})`);
        out.push(words.map(wordProblem).join('\n'));
    }

    if (config.includeAnswerKey) {
        out.push('#pagebreak()');
        out.push('#counter(page).update(1)#metadata(none) <answer-key-start>');
        out.push(`#align(center, text(size: 22pt, weight: "bold")[Answer Key])`);
        out.push(`#align(center, text(size: 10pt, fill: luma(100))[#${str(problems.length + ' Questions')}])`);
        out.push('#v(2mm)#line(length: 100%, stroke: 1pt + luma(60))');
        const grid = (items) =>
            `#grid(columns: (1fr,) * 4, row-gutter: 3mm, column-gutter: 4mm,\n${items.map((p) => `  [${answerItem(p)}],`).join('\n')}\n)`;
        if (math.length > 0) {
            if (both) out.push(`#heading-section(${str('Section A: Number Problems')})`);
            out.push(grid(math));
        }
        if (words.length > 0) {
            out.push(`#heading-section(${str(wordsHeading)})`);
            out.push(grid(words));
        }
    }
    return out.join('\n');
}

let engine = null;

async function getEngine() {
    if (engine) return engine;
    engine = (async () => {
        const [{ $typst, TypstSnippet }] = await Promise.all([
            import('@myriaddreamin/typst.ts/contrib/snippet'),
        ]);
        const base = import.meta.env.BASE_URL;
        const fonts = await Promise.all(
            FONT_FILES.map(async (f) => {
                const res = await fetch(`${base}fonts/${f}`);
                if (!res.ok) throw new Error(`Failed to load font ${f}`);
                return new Uint8Array(await res.arrayBuffer());
            })
        );
        $typst.setCompilerInitOptions({ getModule: () => compilerWasmUrl });
        $typst.use(TypstSnippet.disableDefaultFontAssets(), TypstSnippet.preloadFonts(fonts));
        return $typst;
    })();
    engine.catch(() => { engine = null; });
    return engine;
}

export async function generatePdfBlob(problems, config) {
    const $typst = await getEngine();
    const pdf = await $typst.pdf({ mainContent: buildTypstSource(problems, config) });
    if (!pdf) throw new Error('Typst produced no output');
    return new Blob([pdf], { type: 'application/pdf' });
}

export function prefetchPdfEngine() {
    getEngine().catch(() => {});
}

export async function exportToPDF(problems, config) {
    const blob = await generatePdfBlob(problems, config);
    const filename = `worksheet_${new Date().toISOString().split('T')[0]}.pdf`;
    const file = new File([blob], filename, { type: 'application/pdf' });
    const url = URL.createObjectURL(blob);

    const isIOS = /iP(hone|ad|od)/.test(navigator.userAgent) ||
        (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);

    if (isIOS && navigator.canShare?.({ files: [file] })) {
        try {
            await navigator.share({ files: [file], title: filename });
            URL.revokeObjectURL(url);
            return true;
        } catch (e) {
            if (e?.name === 'AbortError') {
                URL.revokeObjectURL(url);
                return true;
            }
        }
    }

    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 60000);
    return true;
}

// Print the same Typst PDF through a hidden iframe so the print dialog opens directly.
// Falls back to opening the PDF in a tab where inline PDF printing isn't supported
// (mobile browsers, or browsers set to download PDFs instead of viewing them).
function printViaIframe(url) {
    return new Promise((resolve, reject) => {
        const iframe = document.createElement('iframe');
        iframe.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0;visibility:hidden';
        const cleanup = () => {
            iframe.remove();
            URL.revokeObjectURL(url);
        };
        iframe.onload = () => {
            try {
                iframe.contentWindow.focus();
                iframe.contentWindow.print();
                resolve();
            } catch (e) {
                cleanup();
                reject(e);
                return;
            }
            setTimeout(cleanup, 5 * 60 * 1000);
        };
        iframe.src = url;
        document.body.appendChild(iframe);
    });
}

export async function printWorksheet(problems, config) {
    const isMobile = /Android|iP(hone|ad|od)/.test(navigator.userAgent) ||
        (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);
    const canPrintInline = !isMobile && navigator.pdfViewerEnabled !== false;

    // The fallback tab is opened synchronously (before awaiting) so popup blockers allow it.
    const win = canPrintInline ? null : window.open('', '_blank');
    try {
        if (canPrintInline) {
            const blob = await generatePdfBlob(problems, config);
            try {
                await printViaIframe(URL.createObjectURL(blob));
                return;
            } catch {
                const url = URL.createObjectURL(blob);
                window.open(url, '_blank');
                setTimeout(() => URL.revokeObjectURL(url), 120000);
                return;
            }
        }
        const blob = await generatePdfBlob(problems, config);
        const url = URL.createObjectURL(blob);
        if (win) win.location.href = url;
        else window.location.href = url;
        setTimeout(() => URL.revokeObjectURL(url), 120000);
    } catch (e) {
        win?.close();
        throw e;
    }
}
