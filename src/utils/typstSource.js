// Builds the Typst source for each worksheet style.
// (Kept separate from typstExporter.js so it has no wasm / browser dependencies.)
import {
    STYLE_PAPER,
    OPERATOR_SYMBOL,
    paperQuestion,
    practiceColumns,
    practiceCellHeightMm,
    sectionMarks,
    instructionLines,
    workingSheetPageCount,
} from './worksheetLayout.js';

export const FONT_FAMILY = 'Noto Sans';

// Typst string literal: safe for arbitrary text (no markup/math interpretation)
const str = (s) => `"${String(s ?? '').replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

const marksLabel = (n) => `${n} ${n === 1 ? 'mark' : 'marks'}`;

// ---------- shared pieces ----------

function prelude(title, { frame = false } = {}) {
    const background = frame
        ? `  background: place(top + left, dx: 7mm, dy: 7mm, rect(width: 100% - 14mm, height: 100% - 14mm, radius: 4mm, stroke: 1.5pt + luma(60))),\n`
        : '';
    return `
#set document(title: ${str(title)})
#set page(
  paper: "a4",
  margin: (x: 15mm, top: 15mm, bottom: 22mm),
${background}  footer: context {
    set text(size: 9pt, fill: luma(100), style: "italic")
    line(length: 100%, stroke: 0.5pt + luma(200))
    v(-1mm)
    let ak = query(<answer-key-start>)
    let in-key = ak.len() > 0 and here().page() >= ak.first().location().page()
    let total = if ak.len() == 0 or in-key { counter(page).final().first() } else { ak.first().location().page() - 1 }
    grid(columns: (1fr, 1fr), align: (left, right),
      [Page #counter(page).get().first() of #total],
      [Generated by WorksheetLoom.com])
  },
)
#set text(font: ${str(FONT_FAMILY)}, size: 11pt, fill: luma(40), lang: "en")
#set par(leading: 0.7em)
#let heading-section(t) = block(above: 6mm, below: 5mm, sticky: true, text(size: 13pt, weight: "bold", t))
#let heading-marks(t, m) = block(above: 6mm, below: 5mm, sticky: true, width: 100%, grid(columns: (1fr, auto), align: (left, right + bottom), text(size: 13pt, weight: "bold", t), text(size: 10pt, weight: "bold", fill: luma(90), m)))
#let meta-field(label, w) = box(width: w)[#label #box(width: 1fr, stroke: (bottom: 0.6pt + luma(60)), height: 1em)]
`;
}

const metaRow = `#grid(columns: (3fr, 2fr, 2fr), column-gutter: 8mm,
  meta-field("Name:", 100%), meta-field("Class:", 100%), meta-field("Date:", 100%))`;

function answerItem(p) {
    return `#block(breakable: false)[#text(weight: "bold")[#${str(p.number + '.')}] #h(1mm) #${str(p.answer)}]`;
}

function answerKey(problems, math, words, wordsHeading, both) {
    const out = [];
    out.push('#pagebreak()');
    out.push('#counter(page).update(1)#metadata(none) <answer-key-start>');
    out.push(`#align(center, text(size: 22pt, weight: "bold")[Answer Key])`);
    out.push(`#align(center, text(size: 10pt, fill: luma(100))[#${str(problems.length + ' Questions')}])`);
    out.push('#v(2mm)#line(length: 100%, stroke: 1pt + luma(60))');
    const grid = (items) =>
        `#grid(columns: (1fr,) * 4, row-gutter: 3mm, column-gutter: 4mm,\n${items.map((p) => `  [${answerItem(p)}],`).join('\n')}\n)`;
    if (math.length > 0) {
        if (both) out.push(`#heading-section(${str('Section A: Number Problems')})`);
        out.push(grid(math));
    }
    if (words.length > 0) {
        out.push(`#heading-section(${str(wordsHeading)})`);
        out.push(grid(words));
    }
    return out;
}

// ---------- Practice Sheet ----------

function practiceCell(p) {
    const [a, b] = p.operands;
    let body;
    if (p.type === 'division') {
        body = `longdiv(${str(a)}, ${str(b)})`;
    } else {
        const n = Math.max(String(a).length, String(b).length);
        body = `stacked(${str(a)}, ${str(OPERATOR_SYMBOL[p.type])}, ${str(b)}, ${n})`;
    }
    return `  [#place(top + left, dx: 1.5mm, dy: 1mm, text(size: 8pt, weight: "bold", fill: luma(110))[#${str(p.number + '.')}])#align(center + horizon, ${body})],`;
}

function practiceWord(p, area) {
    const answer =
        area === 'box'
            ? `#pad(left: 10mm, rect(width: 70mm, height: 12mm, radius: 2mm, stroke: 1pt + luma(60), inset: 2mm, text(size: 9pt, fill: luma(120))[Answer:]))`
            : `#pad(left: 10mm)[#v(7mm)#line(length: 100%, stroke: 0.5pt + luma(150))#v(7mm)#line(length: 100%, stroke: 0.5pt + luma(150))]`;
    return `#block(breakable: false, below: 6mm)[#grid(columns: (9mm, 1fr), column-gutter: 1mm, text(weight: "bold")[#${str(p.number + '.')}], text(size: 12pt)[#${str(p.question)}])\n${answer}]`;
}

function buildPractice(problems, config, math, words, wordsHeading) {
    const both = math.length > 0 && words.length > 0;
    const title = config.worksheetTitle || 'Worksheet';
    const out = [prelude(title, { frame: true })];

    out.push(`
#let stacked(a, op, b, n) = {
  set text(size: 22pt, weight: "bold")
  set par(leading: 0em, spacing: 0.15em)
  box(width: (n + 1.3) * 0.62em, {
    align(right, a)
    grid(columns: (auto, 1fr), op, align(right, b))
    v(0.1em)
    line(length: 100%, stroke: 1.6pt)
  })
}
#let longdiv(dividend, divisor) = {
  set text(size: 20pt, weight: "bold")
  stack(dir: ttb, v(7mm), grid(columns: (auto, auto), column-gutter: 1.5mm, align: bottom, divisor,
    box(stroke: (top: 1.6pt, left: 1.6pt), inset: (left: 2mm, top: 0.5mm, rest: 0pt), dividend)))
}

#align(center, text(size: 28pt, weight: "bold", ${str(title)}))
#v(1mm)
${metaRow}
#v(3mm)
#line(length: 100%, stroke: 1.5pt + luma(60))
#v(1mm)
`);

    if (math.length > 0) {
        if (both) out.push(`#heading-section(${str('Section A: Number Problems')})`);
        const cols = practiceColumns(math);
        const cells = math.map(practiceCell);
        // pad the last row so every cell keeps its border
        while (cells.length % cols !== 0) cells.push('  [],');
        out.push(
            `#grid(columns: (1fr,) * ${cols}, rows: (${practiceCellHeightMm(math)}mm,), stroke: 0.8pt + luma(60),\n${cells.join('\n')}\n)`
        );
    }
    if (words.length > 0) {
        out.push(`#heading-section(${str(wordsHeading)})`);
        out.push(words.map((p) => practiceWord(p, config.wordAnswerArea)).join('\n'));
    }
    return out;
}

// ---------- Question Paper ----------

function paperQuestionBlock(p, marks, size) {
    return `pq(${str(p.number + '.')}, ${str(paperQuestion(p))}, ${str('[' + marks + ']')}, ${size}pt)`;
}

function workingSheet(config, index, count) {
    const label = count > 1 ? `Working Sheet (${index + 1} of ${count})` : 'Working Sheet';
    const area =
        config.workingSheet === 'grid'
            ? `#box(width: 180mm, height: 215mm, {
  for i in range(0, 37) { place(top + left, dx: i * 5mm, line(angle: 90deg, length: 215mm, stroke: 0.3pt + luma(190))) }
  for j in range(0, 44) { place(top + left, dy: j * 5mm, line(length: 180mm, stroke: 0.3pt + luma(190))) }
})`
            : `#stack(dir: ttb, spacing: 9mm, ..range(24).map(_ => line(length: 100%, stroke: 0.4pt + luma(170))))`;
    return [
        '#pagebreak()',
        `#text(size: 18pt, weight: "bold")[#${str(label)}]`,
        '#v(1mm)',
        `#grid(columns: (3fr, 2fr), column-gutter: 8mm, meta-field("Name:", 100%), meta-field("Date:", 100%))`,
        '#v(2mm)#line(length: 100%, stroke: 1pt + luma(60))#v(4mm)',
        area,
    ];
}

function buildPaper(problems, config, math, words, wordsHeading) {
    const both = math.length > 0 && words.length > 0;
    const title = config.worksheetTitle || 'Worksheet';
    const m = sectionMarks(problems, config);
    const out = [prelude(title)];

    out.push(`
#let pq(n, q, marks, size) = block(breakable: false, grid(columns: (9mm, 1fr, auto), column-gutter: 1mm,
  text(weight: "bold", size: 12pt, n), text(size: size, q), text(size: 9pt, fill: luma(90), marks)))

#align(center, text(size: 24pt, weight: "bold", ${str(title)}))
#v(2mm)
${metaRow}
#v(3mm)
${config.timeAllowed?.trim()
        ? `#grid(columns: (1fr, 1fr), align: (left, right), [*Time allowed:* #${str(config.timeAllowed.trim())}], [*Total marks:* #${str(m.total)}])`
        : `#align(right)[*Total marks:* #${str(m.total)}]`}
#v(2mm)
#line(length: 100%, stroke: 1pt + luma(60))
#v(3mm)
`);

    const instructions = instructionLines(config);
    if (instructions.length > 0) {
        out.push(
            `#block(width: 100%, stroke: 0.6pt + luma(120), inset: 3mm, radius: 1mm, below: 2mm)[#text(size: 9pt, weight: "bold")[GENERAL INSTRUCTIONS]\n#v(1mm)\n#text(size: 10pt)[#list(tight: true, ${instructions.map(str).join(', ')})]]`
        );
    }

    if (math.length > 0) {
        out.push(
            `#heading-marks(${str(both ? 'Section A: Number Problems' : 'Questions')}, ${str('[' + marksLabel(m.totalA) + ']')})`
        );
        out.push(`#grid(columns: (1fr, 1fr), column-gutter: 14mm, row-gutter: 5mm,\n${math.map((p) => '  ' + paperQuestionBlock(p, m.marksA, 16) + ',').join('\n')}\n)`);
    }
    if (words.length > 0) {
        out.push(`#heading-marks(${str(wordsHeading)}, ${str('[' + marksLabel(m.totalB) + ']')})`);
        out.push(words.map((p) => '#block(below: 5mm, ' + paperQuestionBlock(p, m.marksB, 12) + ')').join('\n'));
    }

    if (config.workingSheet !== 'none') {
        const count = workingSheetPageCount(problems);
        for (let i = 0; i < count; i++) out.push(...workingSheet(config, i, count));
    }
    return out;
}

// ---------- entry point ----------

export function buildTypstSource(problems, config) {
    const math = problems.filter((p) => !p.isWordProblem);
    const words = problems.filter((p) => p.isWordProblem);
    const both = math.length > 0 && words.length > 0;
    const wordsHeading = math.length > 0 ? 'Section B: Word Problems' : 'Word Problems';

    const build = config.worksheetStyle === STYLE_PAPER ? buildPaper : buildPractice;
    const out = build(problems, config, math, words, wordsHeading);

    if (config.includeAnswerKey) {
        out.push(...answerKey(problems, math, words, wordsHeading, both));
    }
    return out.join('\n');
}
